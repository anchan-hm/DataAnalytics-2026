# calculating tip amount on restaurant bill given the tip percentage

# variables
bill = 38.50
tip_percentage = 0.20 # 20% tip 

# calculating the tip amount
tip_amount = bill * tip_percentage

# displaying the results
print("The tip on a $"+str(bill) + " restaurant bill is $"+str(tip_amount))
# The tip on a $38.5 restaurant bill is $7.7