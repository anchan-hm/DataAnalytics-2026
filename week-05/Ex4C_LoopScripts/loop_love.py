# creating a loop for love

# list for words the mean "great"
great = ["amazing", "awesome", "excellent", "outstanding", "steller"]

# using "for" to loop through list
for word in great:
    print("Loops are", word + "!")

# final print when loop is finished
print("I <3 loops")
